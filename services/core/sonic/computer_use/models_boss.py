"""Data models for the Boss Agent + SubAgents orchestration system.

The Boss Agent is a strategic orchestrator that decomposes objectives into
phases, dispatches focused sub-missions to SubAgents (ComputerUseAgent workers),
collects their outputs, aggregates findings, and plans next phases until the
objective is complete.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel, Field, model_validator


def _now() -> str:
    return datetime.now(UTC).isoformat()


def _new_id(prefix: str = "boss") -> str:
    return f"{prefix}-{uuid.uuid4().hex[:8]}"


class SubMission(BaseModel):
    """A focused task assigned to a SubAgent or Sub-Planner."""

    id: str = Field(default_factory=lambda: _new_id("sub"))
    name: str = ""
    goal: str
    role: str = "subagent"
    owned_paths: list[str] = Field(default_factory=list)
    sub_planner: bool = False
    requires_exclusive_display: bool = False
    max_steps: int = 5
    priority: int = 1  # Higher = execute first within a phase
    depends_on: list[str] = Field(default_factory=list)
    plane: str = "gui"  # "gui" (visible desktop actions) | "headless" (terminal/file actions)
    process_mode: str = "deep"
    evidence_context: dict[str, Any] = Field(default_factory=dict)
    status: str = "PENDING"  # PENDING -> RUNNING -> COMPLETED -> FAILED
    enable_llm_decomposition: bool | None = None

    @model_validator(mode="after")
    def _infer_plane_from_goal(self) -> SubMission:
        # Accept previously serialized plane values while routing all visual work
        # to the ordinary shared-desktop worker.
        if "plane" in self.model_fields_set and self.plane:
            plane_lower = str(self.plane).lower().strip()
            if plane_lower == "browser":
                self.plane = "gui"
                return self
            if plane_lower in ("gui", "headless"):
                self.plane = plane_lower
                return self

        try:
            from sonic.llm.laya_engine import get_laya_engine

            chosen_plane, prob = get_laya_engine().decide_execution_plane(self.goal or "")
            self.plane = chosen_plane if prob > 0.50 and chosen_plane in ("gui", "headless") else "gui"
        except Exception:
            self.plane = "gui"
        return self


class SubMissionResult(BaseModel):
    """Output collected from a completed SubAgent or Sub-Planner."""

    sub_mission_id: str
    agent_id: str = ""
    # Stable, run-unique worker identity (e.g. "worker-1-a1b2c3"). The positional
    # ``agent_id`` restarts per Boss run, so it cannot be used to address one
    # specific worker across a persisted session; ``agent_uid`` can.
    agent_uid: str = ""
    agent_name: str = ""
    goal: str
    role: str = "worker"
    owned_paths: list[str] = Field(default_factory=list)
    traces: list[Any] = Field(default_factory=list)
    findings_summary: str = ""
    success: bool = False
    key_discoveries: list[str] = Field(default_factory=list)
    actions_taken: int = 0
    duration_seconds: float = 0.0
    evidence_verified: bool = False
    judge_verdict: str = "UNVERIFIED"  # CONFIRMED | FALSIFIED | BENIGN | INCONCLUSIVE | UNVERIFIED
    judge_notes: str = ""
    remediation_blueprint: dict[str, Any] = Field(default_factory=dict)  # Self-correcting fix plan generated by JudgeAgent
    sub_tree_report: Any = None
    status: str = "FAILED"  # SUCCESS | FAILED | TIMED_OUT | BLOCKED | WAITING_FOR_HUMAN
    waiting_for_human: bool = False
    waiting_for_human_reason: str = ""


SubAgentReport = SubMissionResult


class Phase(BaseModel):
    """A batch of SubMissions dispatched together by the Boss."""

    phase_number: int
    name: str = ""
    thinking: str = ""  # Boss's strategic reasoning for creating this phase
    sub_missions: list[SubMission] = Field(default_factory=list)
    results: list[SubMissionResult] = Field(default_factory=list)
    summary: str = ""  # Synthesized intelligence summary from this phase
    status: str = "PENDING"  # PENDING -> RUNNING -> COMPLETED
    started_at: str = ""
    completed_at: str = ""


class BossThinking(BaseModel):
    """A recorded thinking entry from the Boss Agent."""

    id: str = Field(default_factory=lambda: _new_id("think"))
    phase: int
    thinking_type: str  # strategic_decomposition | findings_analysis | reaction_planning | completion_check | final_synthesis
    content: str
    timestamp: str = Field(default_factory=_now)
    duration_seconds: float = 0.0


class BossReport(BaseModel):
    """Final structured report from the Boss Agent after orchestration completes."""

    objective: str
    status: str = "INCOMPLETE"  # COMPLETE | INCOMPLETE | PARTIAL | WAITING_FOR_HUMAN
    phases: list[Phase] = Field(default_factory=list)
    thinking_log: list[BossThinking] = Field(default_factory=list)
    all_traces: list[Any] = Field(default_factory=list)
    total_sub_agents: int = 0
    total_actions: int = 0
    total_phases: int = 0
    findings_summary: str = ""
    duration_seconds: float = 0.0
    replay_metrics: dict[str, Any] = Field(default_factory=dict)
    replay_quality_gate_passed: bool = False
    dispatch_decision: dict[str, Any] = Field(default_factory=dict)
    waiting_for_human: bool = False
    waiting_for_human_reason: str = ""
